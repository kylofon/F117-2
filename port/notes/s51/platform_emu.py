"""S5.1: reference vectors for the platform layer, computed by running the ORIGINAL code under Unicorn.

Runs library routines of the unpacked END.EXE and VGAME.EXE (work/unpacked, python tools/unlzexe.py):
  rand/srand/rand_n (END 52DC/52CA/3E45), dist_approx (END 452C), joy_scale (END 441D, register arg SI),
  rtl_aFldiv/aFlmul (VGAME F392/F42C), rtl_aFlshl/aFlshr/aFulshr (VGAME F45E/F46A/F50E).
Writes f117port/src/platform/selftest_vectors.h (numbers only, no game data), which selftest.c compares the port against
bit for bit. Re-run: python port/notes/s51/platform_emu.py
"""
import struct, sys, os, random
from unicorn import *
from unicorn.x86_const import *

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))


class Img:
    def __init__(self, name, dseg):
        d = open(os.path.join(ROOT, 'work', 'unpacked', name), 'rb').read()
        self.dseg = dseg
        uc = self.uc = Uc(UC_ARCH_X86, UC_MODE_16)
        uc.mem_map(0, 0x110000)
        uc.mem_write(0, d[struct.unpack_from('<H', d, 8)[0] * 16:])
        for r in (UC_X86_REG_DS, UC_X86_REG_ES, UC_X86_REG_SS):
            uc.reg_write(r, dseg)
        uc.reg_write(UC_X86_REG_CS, 0)

    def call(self, addr, args=(), regs=None):
        uc = self.uc
        sp = 0xF800
        base = self.dseg * 16
        for a in reversed(args):
            sp -= 2
            uc.mem_write(base + sp, (a & 0xFFFF).to_bytes(2, 'little'))
        sp -= 2
        uc.mem_write(base + sp, (0xFFFF).to_bytes(2, 'little'))
        uc.reg_write(UC_X86_REG_SP, sp)
        uc.reg_write(UC_X86_REG_BP, 0)
        uc.reg_write(UC_X86_REG_CS, 0)
        for r, v in (regs or {}).items():
            uc.reg_write(r, v)
        uc.emu_start(addr, 0xFFFF, count=2000000)
        return uc.reg_read(UC_X86_REG_AX), uc.reg_read(UC_X86_REG_DX)

    def w16(self, off, v):
        self.uc.mem_write(self.dseg * 16 + off, (v & 0xFFFF).to_bytes(2, 'little'))

    def r16(self, off):
        return int.from_bytes(self.uc.mem_read(self.dseg * 16 + off, 2), 'little')


def lo32(ax, dx):
    return (dx << 16 | ax) & 0xFFFFFFFF


def s16(v):
    v &= 0xFFFF
    return v - 0x10000 if v & 0x8000 else v


def main():
    out = ['/* Generated by port/notes/s51/platform_emu.py from the original END.EXE / VGAME.EXE under Unicorn. Do not edit. */']
    end = Img('END.EXE', 0x5FA)
    vg = Img('VGAME.EXE', 0x1E23)

    # ---- rand: srand(seed); 8 x rand(); then rand_n(6), rand_n(100), rand_n(32767), rand_n(-5), rand_n(1)
    seeds = [0, 1, 0x1234, 0xFFFF, 12345, 0x7FFF]
    ns = [6, 100, 32767, -5, 1]
    out.append('static const struct { unsigned seed; int rnd[8]; int rn[5]; } vec_rand[] = {')
    for s in seeds:
        end.call(0x52CA, [s])
        r = [end.call(0x52DC)[0] for _ in range(8)]
        rn = [s16(end.call(0x3E45, [n])[0]) for n in ns]
        out.append('    { %d, { %s }, { %s } },' % (s, ', '.join(map(str, r)), ', '.join(map(str, rn))))
    out.append('};')
    out.append('static const int vec_rand_n[] = { %s };' % ', '.join(map(str, ns)))

    # ---- dist_approx(x1, y1, x2, y2)
    random.seed(117)
    cases = [(0, 0, 0, 0), (10, 0, 0, 0), (0, 10, 0, 0), (3, 4, 0, 0), (-3, -4, 0, 0), (100, 100, 0, 0),
             (32767, -32768, 0, 0), (-32768, -32768, 0, 0), (1000, 1, 0, 0), (1, 1000, 0, 0), (7, 7, 7, 7)]
    cases += [tuple(random.randint(-32768, 32767) for _ in range(4)) for _ in range(20)]
    cases += [tuple(random.randint(-300, 300) for _ in range(4)) for _ in range(20)]
    out.append('static const struct { int x1, y1, x2, y2, r; } vec_dist[] = {')
    for c in cases:
        r = s16(end.call(0x452C, list(c))[0])
        out.append('    { %d, %d, %d, %d, %d },' % (c + (r,)))
    out.append('};')

    # ---- long helpers (VGAME): pascal-ish, args pushed in C order: bp+4 = a lo, +6 = a hi, +8 = b lo, +10 = b hi
    def arg32(v):
        v &= 0xFFFFFFFF
        return [v & 0xFFFF, v >> 16]
    pairs = [(7, 2), (-7, 2), (7, -2), (-7, -2), (0x7FFFFFFF, 3), (-0x80000000, 1), (-0x80000000, -1), (123456789, 1000),
             (-123456789, 1000), (1000, 123456789), (65535, 65535), (0x12345678, 0x9ABC), (-1, 1), (0, 5)]
    out.append('static const struct { long a, b; long q; } vec_ldiv[] = {')
    for a, b in pairs:
        ax, dx = vg.call(0xF392, arg32(a) + arg32(b))
        q = lo32(ax, dx)
        out.append('    { %dL, %dL, %dL },' % (a, b, q - (1 << 32) if q & 0x80000000 else q))
    out.append('};')
    mpairs = [(0x10000, 0x10000), (123456, 789), (-5, 7), (0x7FFFFFFF, 2), (0x12345678, -0x65432110), (-1, -1), (0, 99999)]
    out.append('static const struct { long a, b; long p; } vec_lmul[] = {')
    for a, b in mpairs:
        ax, dx = vg.call(0xF42C, arg32(a) + arg32(b))
        p = lo32(ax, dx)
        out.append('    { %dL, %dL, %dL },' % (a, b, p - (1 << 32) if p & 0x80000000 else p))
    out.append('};')
    shifts = [(0x12345678, n) for n in (0, 1, 4, 15, 16, 17, 31, 32, 33, 40)] + [(-0x12345678, n) for n in (1, 4, 31, 32, 40)] + [(0x80000001 - (1 << 32), n) for n in (1, 31, 33)]
    out.append('static const struct { long a; int n; long shl, sar; unsigned long shr; } vec_shift[] = {')
    for a, n in shifts:
        res = []
        for addr in (0xF45E, 0xF46A, 0xF50E):
            # shifts take AX/DX (value) and CL (count) in registers
            ax, dx = vg.call(addr, [], {UC_X86_REG_AX: a & 0xFFFF, UC_X86_REG_DX: (a >> 16) & 0xFFFF, UC_X86_REG_CX: n})
            v = lo32(ax, dx)
            res.append(v)
        sg = lambda v: v - (1 << 32) if v & 0x80000000 else v
        out.append('    { %dL, %d, %dL, %dL, %dUL },' % (a, n, sg(res[0]), sg(res[1]), res[2]))
    out.append('};')

    # ---- joy_scale on END: table at 23C4 (min +00, max +08, centre +10, slope lo +18, slope hi +20, raw +28, out +30)
    BASE = 0x23C4
    tbl = {0x00: 500, 0x08: 1500, 0x10: 1000, 0x18: 500, 0x20: 500}
    for k, v in tbl.items():
        end.w16(BASE + k, v)
    seq = [1000, 1250, 750, 1499, 1500, 1499, 600, 500, 501, 1600, 1550, 400, 450, 1000, 1001, 999, 1200, 1300]
    out.append('static const struct { unsigned raw, out, min, max, slo, shi; } vec_joy[] = {')
    for raw in seq:
        end.w16(BASE + 0x28, raw)
        end.call(0x441D, [], {UC_X86_REG_SI: 0})
        o = int.from_bytes(end.uc.mem_read(end.dseg * 16 + BASE + 0x30, 1), 'little')
        out.append('    { %d, %d, %d, %d, %d, %d },' % (raw, o, end.r16(BASE), end.r16(BASE + 8), end.r16(BASE + 0x18), end.r16(BASE + 0x20)))
    out.append('};')

    dst = os.path.join(ROOT, 'f117port', 'src', 'platform', 'selftest_vectors.h')
    open(dst, 'w', newline='\n').write('\n'.join(out) + '\n')
    print('wrote', dst, len(out), 'lines')


if __name__ == '__main__':
    main()
