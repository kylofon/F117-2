/* CP437 double-line box characters in an 8 x 16 cell: vertical rails at x = 2 and 5, horizontal rails at y = 5 and 10.
 * Each glyph is a list of rectangles {x0, x1, y0, y1} (inclusive). */
typedef struct { u8 x0, x1, y0, y1; } BoxRect;
typedef struct { u8 ch; BoxRect r[4]; } BoxGlyph;
static const BoxGlyph box_glyphs[] = {
    { 0xC9, { {2, 2, 5, 15}, {5, 5, 10, 15}, {2, 7, 5, 5}, {5, 7, 10, 10} } },   /* top-left corner */
    { 0xBB, { {5, 5, 5, 15}, {2, 2, 10, 15}, {0, 5, 5, 5}, {0, 2, 10, 10} } },   /* top-right */
    { 0xC8, { {2, 2, 0, 10}, {5, 5, 0, 5}, {2, 7, 10, 10}, {5, 7, 5, 5} } },     /* bottom-left */
    { 0xBC, { {5, 5, 0, 10}, {2, 2, 0, 5}, {0, 5, 10, 10}, {0, 2, 5, 5} } },     /* bottom-right */
    { 0xCD, { {0, 7, 5, 5}, {0, 7, 10, 10}, {0, 0, 0, 0}, {0, 0, 0, 0} } },      /* horizontal */
    { 0xBA, { {2, 2, 0, 15}, {5, 5, 0, 15}, {0, 0, 0, 0}, {0, 0, 0, 0} } },      /* vertical */
};

static u8 box_row(u8 ch, int y)
{
    for (size_t g = 0; g < sizeof box_glyphs / sizeof box_glyphs[0]; g++) {
        if (box_glyphs[g].ch != ch) continue;
        u8 b = 0;
        for (int k = 0; k < 4; k++) {
            const BoxRect *r = &box_glyphs[g].r[k];
            if (r->x0 == 0 && r->x1 == 0 && r->y0 == 0 && r->y1 == 0 && k >= 2) continue;     /* unused slot */
            if (y < r->y0 || y > r->y1) continue;
            for (int x = r->x0; x <= r->x1; x++) b |= (u8)(0x80 >> x);
        }
        return b;
    }
    return 0;
}

static const u32 cga[16] = {
    0x000000, 0x0000AA, 0x00AA00, 0x00AAAA, 0xAA0000, 0xAA00AA, 0xAA5500, 0xAAAAAA,
    0x555555, 0x5555FF, 0x55FF55, 0x55FFFF, 0xFF5555, 0xFF55FF, 0xFFFF55, 0xFFFFFF,
};

void vga_text_render(u32 *out)
{
    const u8 *text = mem + VGA_TEXT_BASE;
    for (int row = 0; row < 25; row++)
        for (int col = 0; col < 80; col++) {
            u8 ch = text[(row * 80 + col) * 2], at = text[(row * 80 + col) * 2 + 1];
            u32 fg = cga[at & 15], bg = cga[(at >> 4) & 7];            /* bit 7 = blink: not modelled, the background is 3 bits */
            for (int y = 0; y < 16; y++) {
                u8 bits;
                if (ch >= 0x20 && ch <= 0x7E) {
                    u8 r = font8[ch - 0x20][y >> 1];                    /* bit 0 = leftmost: reverse to bit 7 */
                    bits = 0;
                    for (int x = 0; x < 8; x++) if (r & (1 << x)) bits |= (u8)(0x80 >> x);
                } else {
                    bits = box_row(ch, y);
                }
                u32 *o = out + (size_t)(row * 16 + y) * 640 + (size_t)col * 8;
                for (int x = 0; x < 8; x++) o[x] = (bits & (0x80 >> x)) ? fg : bg;
            }
        }
}
